# Initiallize  a variable balance=1000. Perform operations using shorthand operators like +=, -=, *=, /= and print the updated balance after each operation.
bal=1000
print("Initial balance: ", bal)
bal += 500
print("Balance after addition: ", bal)
bal -= 200
print("Balance after subtraction: ", bal)
bal *= 2
print("Balance after multiplication: ", bal)
bal /= 2
print("Balance after division: ", bal)